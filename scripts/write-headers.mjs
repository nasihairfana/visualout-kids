/**
 * Writes `.output/public/_headers` for Cloudflare Pages after `nuxt generate`.
 *
 * The Content-Security-Policy only allows the app's own files, so nothing can load or send
 * anything to another site. Nuxt puts two small inline scripts in every page (an import map and
 * the runtime config, which changes on every build), so their exact SHA-256 hashes are read from
 * the built HTML and added to the policy instead of allowing inline scripts in general.
 */
import { createHash } from 'node:crypto'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const OUT = '.output/public'

async function htmlFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true })
  const nested = await Promise.all(entries.map((e) => {
    const path = join(dir, e.name)
    if (e.isDirectory()) return htmlFiles(path)
    return e.name.endsWith('.html') ? [path] : []
  }))
  return nested.flat()
}

// Inline <script> blocks that the browser executes (JSON data blocks are not scripts, so skip them).
const INLINE_SCRIPT = /<script(?![^>]*\bsrc=)([^>]*)>([\s\S]*?)<\/script>/g
const hashes = new Set()
for (const file of await htmlFiles(OUT)) {
  for (const [, attrs, body] of (await readFile(file, 'utf8')).matchAll(INLINE_SCRIPT)) {
    if (/type="application\/json"/.test(attrs) || !body.trim()) continue
    hashes.add(`'sha256-${createHash('sha256').update(body).digest('base64')}'`)
  }
}

const csp = [
  `default-src 'self'`,
  `script-src 'self' ${[...hashes].join(' ')}`,
  `style-src 'self' 'unsafe-inline'`,
  `img-src 'self' data: blob:`,
  `media-src 'self' blob:`,
  `font-src 'self'`,
  `connect-src 'self'`,
  `worker-src 'self'`,
  `manifest-src 'self'`,
  `object-src 'none'`,
  `base-uri 'self'`,
  `form-action 'none'`,
  `frame-ancestors 'none'`,
].join('; ')

const headers = `# Generated by scripts/write-headers.mjs. Do not edit; it is rewritten on every build.
/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: no-referrer
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), bluetooth=(), browsing-topics=()
  Cross-Origin-Opener-Policy: same-origin

# Always check for a new service worker and manifest, so families get updates.
/sw.js
  Cache-Control: no-cache
/manifest.webmanifest
  Cache-Control: no-cache

# Built files have a content hash in their name and never change.
/_nuxt/*
  Cache-Control: public, max-age=31536000, immutable
`

await writeFile(join(OUT, '_headers'), headers)
console.log(`Wrote ${OUT}/_headers (${hashes.size} inline script hashes)`)
